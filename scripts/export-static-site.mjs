/**
 * Exports the running site as a folder that can be dropped straight onto a static host (Netlify Drop, a plain
 * web server). Unlike export-preview.mjs (relative links for an offline preview), this keeps clean absolute URLs,
 * saves every share image as a .png, adds Google Analytics and Clarity, writes 404.html, robots.txt, sitemap.xml
 * and a Netlify _redirects file.
 *
 * Differences from the full Next.js deployment:
 *   - Shopping links point straight at the retailer URL resolved at export time (no /out/ redirect, no click log).
 *   - Shared My Jerseys links (/j/{code}/) are drawn in the browser from one static page, so their link preview
 *     shows the general "What's your jersey count?" card instead of each person's own list.
 *
 *   BASE=http://localhost:3000 OUT=site node scripts/export-static-site.mjs
 */
import fs from "node:fs";
import path from "node:path";
import zlib from "node:zlib";

const BASE = process.env.BASE || "http://localhost:3000";
const OUT = process.env.OUT || "site";
const GA_ID = process.env.NEXT_PUBLIC_GA_MEASUREMENT_ID || "G-G3NLPZMT2W";
const CLARITY_ID = process.env.NEXT_PUBLIC_CLARITY_ID || "z0yme16q8j";
fs.rmSync(OUT, { recursive: true, force: true });

const write = (rel, data) => {
  const file = path.join(OUT, rel);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, data);
};

const tags = `<script async src="https://www.googletagmanager.com/gtag/js?id=${GA_ID}"></script><script>window.dataLayer=window.dataLayer||[];function gtag(){dataLayer.push(arguments);}gtag('js',new Date());gtag('config','${GA_ID}');</script><script>(function(c,l,a,r,i,t,y){c[a]=c[a]||function(){(c[a].q=c[a].q||[]).push(arguments)};t=l.createElement(r);t.async=1;t.src="https://www.clarity.ms/tag/"+i;y=l.getElementsByTagName(r)[0];y.parentNode.insertBefore(t,y);})(window,document,"clarity","script","${CLARITY_ID}");</script>`;

const searchScript = `<script>(function(){var d=document.getElementById('search-index');if(!d)return;var items=JSON.parse(d.textContent),inp=document.getElementById('q-page'),list=document.querySelector('.results'),form=inp&&inp.form;if(!inp)return;function n(s){return s.toLowerCase().normalize('NFD').replace(/[\\u0300-\\u036f]/g,'')}function run(){var w=n(inp.value).split(/\\s+/).filter(Boolean);list.innerHTML='';if(!w.length)return;items.filter(function(i){var t=n(i.terms);return w.every(function(x){return t.indexOf(x)>-1})}).slice(0,30).forEach(function(i){var li=document.createElement('li');li.innerHTML='<a href="'+i.href+'"><span><strong></strong><br><span class="shop-note"></span></span><span class="shop-note"></span></a>';li.querySelector('strong').textContent=i.name;var s=li.querySelectorAll('.shop-note');s[0].textContent=i.sub;s[1].textContent=i.rank;list.appendChild(li)})}inp.addEventListener('input',run);form.addEventListener('submit',function(e){e.preventDefault();run()});inp.value=new URLSearchParams(location.search).get('q')||'';run()})();</script>`;

// Crawl every internal page.
const pages = new Map();
const queue = ["/", "/search/", "/my-jerseys/"];
const assets = new Set();
while (queue.length) {
  const p = queue.shift();
  if (pages.has(p)) continue;
  const r = await fetch(BASE + p);
  if (r.status !== 200) { console.warn("skip", p, r.status); pages.set(p, null); continue; }
  const html = await r.text();
  pages.set(p, html);
  for (const m of html.matchAll(/href="(\/[^"#?]*)/g)) {
    const h = m[1];
    if (h.startsWith("/_next/")) { assets.add(h); continue; }
    if (h.startsWith("/out/") || h.startsWith("/j/") || /\.(svg|png|ico|xml|txt|js|json)$/.test(h) || h.includes("opengraph-image") || h.includes("apple-icon")) continue;
    if (!pages.has(h) && !queue.includes(h)) queue.push(h);
  }
}

const outCache = new Map();
async function resolveOut(href) {
  if (!outCache.has(href)) {
    const r = await fetch(BASE + href, { redirect: "manual" });
    outCache.set(href, r.headers.get("location") || "#");
  }
  return outCache.get(href);
}

// Share images and icons are generated by Next at request time; save each once as a static .png.
const imageCache = new Map();
async function saveImage(url, name) {
  const u = new URL(url, BASE);
  const key = u.pathname + u.search;
  if (!imageCache.has(key)) {
    const r = await fetch(BASE + key);
    if (!r.ok) { console.warn("image", key, r.status); imageCache.set(key, url); return url; }
    write(name, Buffer.from(await r.arrayBuffer()));
    imageCache.set(key, "/" + name);
  }
  return imageCache.get(key);
}

async function processPage(p, html) {
  html = html.replace(/<script(?![^>]*(?:type="application\/(?:ld\+json|json)"|data-keep))[^>]*>[\s\S]*?<\/script>/g, "");
  html = html.replace(/<link[^>]+as="script"[^>]*\/?>/g, "");
  html = html.replace(/(<script type="application\/json" id="search-index">[\s\S]*?<\/script>)/, `$1${searchScript}`);
  for (const m of [...html.matchAll(/href="(\/out\/[^"]+)"/g)]) html = html.replace(m[0], `href="${(await resolveOut(m[1])).replace(/&/g, "&amp;")}"`);
  html = html.replace(/\/_next\/static\//g, "/assets/");
  const slug = p === "/" ? "home" : p.replace(/^\/|\/$/g, "").replace(/\//g, "-");
  for (const m of [...html.matchAll(/<meta (?:property="og:image"|name="twitter:image") content="([^"]+)"/g)]) {
    const local = await saveImage(m[1].replace(/&amp;/g, "&"), `share/${slug}.png`);
    html = html.split(m[1]).join(local.startsWith("/") ? SITE + local : local);
  }
  for (const m of [...html.matchAll(/<link rel="apple-touch-icon" href="([^"]+)"/g)]) {
    const local = await saveImage(m[1].replace(/&amp;/g, "&"), "apple-icon.png");
    html = html.split(m[1]).join(local);
  }
  return html.replace("</head>", `${tags}</head>`);
}

let SITE = "";

let count = 0;
for (const [p, html0] of pages) {
  if (!html0) continue;
  SITE = (html0.match(/<meta property="og:url" content="(https?:\/\/[^/"]+)/) || [, ""])[1];
  write(path.join(p, "index.html"), await processPage(p, html0));
  count++;
}

// 404 page.
const nf = await fetch(BASE + "/this-page-does-not-exist/");
write("404.html", await processPage("/404/", await nf.text()));

// Shared My Jerseys page: one static page that public/my-jerseys.js fills in from the code in the address.
const sample = "z" + zlib.deflateRawSync(Buffer.from("Joe\nnfl\tJosh Allen")).toString("base64url");
let jhtml = await (await fetch(`${BASE}/j/${sample}/`)).text();
jhtml = jhtml.replace(/<main[\s\S]*<\/main>/, `<main id="main" data-page-type="shared_jerseys">
<section class="mj-hero"><div class="wrap"><p class="kicker">Jersey collection</p><h1 id="mj-shared-h1">Jersey count</h1></div></section>
<div class="wrap mj-shared" id="mj-shared" data-leagues='${JSON.stringify(Object.fromEntries([...(pages.get("/my-jerseys/") || "").matchAll(/data-league="(\w+)" aria-selected="\w+" style="--lg:(#[0-9a-f]+)">(\w+)</g)].map((m) => [m[1], { name: m[3], accent: m[2] }])))}'>
<div class="mj-card"><div class="mj-groups" id="mj-shared-groups"><p class="mj-empty">Loading…</p></div></div>
<div class="mj-cta"><p>What&#x27;s your jersey count?</p><a class="btn-shop" href="/my-jerseys/"><span class="cta-text">Count my jerseys</span></a><a class="mj-sec" href="/">See the top selling jerseys</a></div>
</div></main>`);
const mj = pages.get("/my-jerseys/");
const mjImage = (mj.match(/<meta property="og:image" content="([^"]+)"/) || [])[1];
jhtml = jhtml
  .replace(/<title>[^<]*<\/title>/, "<title>What&#x27;s your jersey count? | Top Selling Jerseys</title>")
  .replace(/(<meta (?:property="og:title"|name="twitter:title") content=")[^"]*"/g, `$1What&#x27;s your jersey count?"`)
  .replace(/(<meta (?:name="description"|property="og:description"|name="twitter:description") content=")[^"]*"/g, `$1See this jersey collection, then count and share your own from the NFL, NBA, MLB, NHL and MLS."`)
  .replace(/<meta property="og:image:alt" content="[^"]*"\/>/, "")
  .replace(/(<meta (?:property="og:image"|name="twitter:image") content=")[^"]*"/g, `$1${mjImage}"`)
  .replace(/<meta property="og:url"[^>]*>/, "")
  .replace(/<link rel="canonical"[^>]*>/, "");
write("j/index.html", await processPage("/j/", jhtml));

// CSS and fonts.
for (const a of [...assets].filter((a) => a.endsWith(".css"))) {
  let css = await (await fetch(BASE + a)).text();
  for (const m of css.matchAll(/url\((?:\/_next\/static\/media\/|\.\.\/media\/)([^)]+)\)/g)) {
    write(path.join("assets/media", m[1]), Buffer.from(await (await fetch(`${BASE}/_next/static/media/${m[1]}`)).arrayBuffer()));
  }
  write(a.replace("/_next/static/", "/assets/"), css.replace(/url\(\/_next\/static\/media\//g, "url(../media/"));
}

// Static files, crawler files and host rules.
fs.copyFileSync("public/icon.svg", path.join(OUT, "icon.svg"));
fs.copyFileSync("public/my-jerseys.js", path.join(OUT, "my-jerseys.js"));
fs.cpSync("public/player-index", path.join(OUT, "player-index"), { recursive: true });
write("robots.txt", await (await fetch(BASE + "/robots.txt")).text());
write("sitemap.xml", await (await fetch(BASE + "/sitemap.xml")).text());
const leagues = ["nfl", "nba", "mlb", "nhl", "mls"];
write("_redirects", [
  ...leagues.flatMap((l) => [`/${l}  /top-selling-${l}-jerseys/  301`, `/${l}/*  /players/:splat  301`]),
  "/j/*  /j/index.html  200",
].join("\n") + "\n");
console.log(`Exported ${count} pages to ${OUT}/ (${outCache.size} shopping links, ${imageCache.size} images)`);
